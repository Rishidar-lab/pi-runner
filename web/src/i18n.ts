const dicts: Record<Lang, Record<string, string>> = { en, ta };
let current: Lang = 'en';

try {
  const saved = typeof localStorage !== 'undefined' ? localStorage.getItem('kr-lang') : null;
  if (saved === 'en' || saved === 'ta') current = saved;
} catch { /* storage unavailable — default English */ }

export function getLang(): Lang { return current; }

export function setLang(lang: Lang): void {
  current = lang;
  try { localStorage.setItem('kr-lang', lang); } catch { /* ignore */ }
  document.documentElement.lang = lang === 'ta' ? 'ta' : 'en';
}

export function toggleLang(): Lang {
  setLang(current === 'en' ? 'ta' : 'en');
  return current;
}

/** Translate a key, with optional {placeholder} interpolation. */
export function t(key: string, vars?: Record<string, string | number>): string {
  const table = dicts[current] || en;
  let s = table[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
